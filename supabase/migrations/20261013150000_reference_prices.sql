-- Reference prices (ADR 0021). A typical US supermarket price for one typical
-- package of each global canonical ingredient, so costs work before a household
-- has priced anything. Shown as "EST" and always outranked by a household's own
-- store price; scaled to the household by calibration from its real prices.
--
-- Shared reference data: readable by every signed-in user, written only by
-- migrations. Package units match each ingredient's default unit (count units
-- don't convert between each other), validated when this seed was generated.
-- Refresh by adding a migration with a newer as_of; it upserts.

create table public.reference_price (
  canonical_ingredient_id uuid primary key
    references public.canonical_ingredient (id) on delete cascade,
  price_cents integer not null check (price_cents >= 0),
  package_quantity numeric not null check (package_quantity > 0),
  package_unit text not null,
  region text not null default 'US',
  as_of date not null
);

alter table public.reference_price enable row level security;

create policy "reference_price: signed-in read"
  on public.reference_price for select
  to authenticated
  using (true);

